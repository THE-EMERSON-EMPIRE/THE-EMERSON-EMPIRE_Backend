-- Minimal EPDG identity contract for the isolated Neon administrator staging branch.
-- Contains no company, applicant, learner, resume, production, or imported data.
CREATE SCHEMA core;
CREATE SCHEMA epdg;
CREATE SCHEMA portal_security;
REVOKE ALL ON SCHEMA public, core, epdg, portal_security FROM PUBLIC;

CREATE TYPE core.user_role AS ENUM ('admin', 'company', 'intern', 'school');
CREATE TYPE core.admin_role AS ENUM ('admin', 'super_admin');
CREATE TYPE epdg.user_role AS ENUM ('admin', 'company', 'intern', 'school');
CREATE TYPE epdg.admin_role AS ENUM ('admin', 'super_admin');

CREATE TABLE core.branches (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(30) NOT NULL UNIQUE,
  name varchar(100) NOT NULL,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE core.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(150) NOT NULL,
  name varchar(100) NOT NULL,
  password varchar(255) NOT NULL,
  is_verified boolean NOT NULL DEFAULT false,
  verification_token varchar(255),
  token_expires_at timestamp without time zone,
  last_login_at timestamp without time zone,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at timestamp without time zone
);
CREATE UNIQUE INDEX core_users_email_unique_active ON core.users(email) WHERE deleted_at IS NULL;
CREATE TABLE core.user_branch_roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES core.users(id),
  branch_id integer NOT NULL REFERENCES core.branches(id),
  role_name core.user_role NOT NULL,
  admin_role core.admin_role,
  rejection_reason text,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (user_id, branch_id)
);

CREATE TABLE epdg.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(150) NOT NULL,
  name varchar(100) NOT NULL,
  password varchar(255) NOT NULL,
  role epdg.user_role NOT NULL,
  is_verified boolean NOT NULL DEFAULT false,
  verification_token varchar(255),
  token_expires_at timestamptz,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at timestamptz,
  rejection_reason text
);
CREATE UNIQUE INDEX epdg_users_email_unique_active ON epdg.users(email) WHERE deleted_at IS NULL;
CREATE TABLE epdg.admins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES epdg.users(id),
  admin_role epdg.admin_role NOT NULL DEFAULT 'admin',
  force_password_change boolean NOT NULL DEFAULT false
);
CREATE TABLE epdg.schools (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES epdg.users(id),
  school_name varchar(150) NOT NULL,
  email varchar(150),
  is_approved boolean NOT NULL DEFAULT false,
  deleted_at timestamptz
);
CREATE TABLE epdg.companies (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES epdg.users(id),
  company_name varchar(150) NOT NULL,
  email varchar(150),
  is_approved boolean NOT NULL DEFAULT false,
  deleted_at timestamptz
);
CREATE TABLE epdg.intern_profiles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES epdg.users(id),
  school_id integer REFERENCES epdg.schools(id),
  is_approved boolean NOT NULL DEFAULT false,
  rejection_reason text
);

CREATE TABLE portal_security.schema_migrations (
  version text PRIMARY KEY,
  sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  applied_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

ALTER TABLE core.branches ENABLE ROW LEVEL SECURITY;
ALTER TABLE core.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE core.user_branch_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE epdg.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE epdg.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE epdg.schools ENABLE ROW LEVEL SECURITY;
ALTER TABLE epdg.companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE epdg.intern_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE portal_security.schema_migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA core, epdg, portal_security FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA core, epdg, portal_security FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA core, epdg, portal_security FROM PUBLIC;
